CREATE TABLE public.wheel_rounds (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  round_no bigint GENERATED BY DEFAULT AS IDENTITY,
  status text NOT NULL DEFAULT 'betting',
  slots jsonb NOT NULL,
  winning_key text,
  started_at timestamptz NOT NULL DEFAULT now(),
  ends_at timestamptz NOT NULL,
  settled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.wheel_bets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  round_id uuid NOT NULL REFERENCES public.wheel_rounds(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  room_id uuid REFERENCES public.rooms(id) ON DELETE SET NULL,
  slot_key text NOT NULL,
  amount bigint NOT NULL,
  payout bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX wheel_bets_round_idx ON public.wheel_bets (round_id);
CREATE INDEX wheel_bets_user_idx ON public.wheel_bets (user_id, created_at DESC);
CREATE INDEX wheel_rounds_status_idx ON public.wheel_rounds (status, created_at DESC);

